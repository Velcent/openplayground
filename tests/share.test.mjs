import assert from 'node:assert/strict'
import { after, before, test } from 'node:test'
import { sessionSite } from './session-helpers.mjs'
import { until } from './helpers.mjs'
let site
before(async () => { site = await sessionSite() })
after(async () => { await site?.close() })
async function appPage(path = '/honeydew/') {
  const context = await site.browser.newContext()
  const page = await context.newPage()
  // Fulfilled HTML has no network address classification; grant localhost access for this fixture.
  await context.grantPermissions(['local-network-access'], {origin:site.url})
  await page.route(url => url.pathname === new URL(path, site.url).pathname, route => route.fulfill({ contentType:'text/html', body:'<!doctype html><title>App</title><link rel="stylesheet" href="/shell/shell.css"><script type="module" src="/shell/app.js"></script><canvas></canvas>' }))
  await page.goto(new URL(path, site.url).href)
  return page
}

test('share selected files, join with a size preview, and export without overwriting personal files', async () => {
  const a = await appPage()
  await a.evaluate(async () => {
    const store = await import('/shell/store.js')
    await store.write('/Score.txt', new Blob(['score']))
    await store.write('/Private.txt', new Blob(['private']))
  })
  await a.getByRole('button', { name:'Share files', exact:true }).click({ timeout:3000 })
  await a.getByLabel('Your name').fill('Alice')
  await a.getByLabel('Score.txt', {exact:true}).check()
  await a.getByRole('button', { name:'Create session', exact:true }).click()
  const invite = a.getByRole('textbox', {name:'Invitation link'})
  await until(() => invite.count().then(n=>n?invite.inputValue():''), 5000, 'invitation').catch(async e=>{console.error(await a.getByRole('dialog').innerText());throw e})
  const link = await invite.inputValue()
  await a.context().grantPermissions(['local-network-access','clipboard-read','clipboard-write'],{origin:site.url})
  await a.getByRole('button',{name:'Copy link',exact:true}).click()
  assert.equal(await a.evaluate(()=>navigator.clipboard.readText()),link)
  assert.match(link, /#pg-session=/)
  const b = await appPage(link)
  await b.evaluate(async () => { const store = await import('/shell/store.js'); await store.write('/Score.txt', new Blob(['mine'])) })
  await b.getByLabel('Your name').fill('Bob')
  await b.getByRole('button', { name:'Join session', exact:true }).click()
  await b.getByText('1 file · 5 B', {exact:true}).waitFor()
  assert.equal(await b.getByRole('button', {name:'Save a copy to Files'}).isEnabled(), false)
  await b.getByRole('button', {name:'Receive files', exact:true}).click()
  await b.getByRole('button', {name:'Save a copy to Files'}).click()
  await until(() => b.evaluate(async () => (await (await import('/shell/store.js')).list('/')).length === 2))
  assert.deepEqual(await b.evaluate(async () => { const s = await import('/shell/store.js'); return [await (await s.file('/Score.txt')).text(),await (await s.file('/Score (2).txt')).text()] }), ['mine','score'])
  assert.equal(await a.locator('.pg-share-count').textContent(), '2 people')
  assert.equal(await b.locator('.pg-share-count').textContent(), '2 people')
  await a.getByRole('button', {name:'Lock invitations',exact:true}).click()
  await a.getByRole('button', {name:'Unlock invitations',exact:true}).waitFor()
  await a.getByLabel('Access for Bob').selectOption('viewer')
  await until(() => b.locator('.pg-share-person').filter({hasText:'Bob (you)'}).innerText().then(s=>s.includes('viewer')))
  assert.equal(await b.getByRole('button',{name:'Receive files',exact:true}).isVisible(),false)
  assert.equal(await b.getByLabel('Share more files').isVisible(),false)
  await b.setViewportSize({width:390,height:780})
  assert.ok((await b.getByRole('dialog').boundingBox()).width <= 390)
  await b.keyboard.press('Escape')
  assert.equal(await b.getByRole('dialog').count(), 0)
  await b.getByRole('button', {name:'Session: 2 people',exact:true}).click()
  await b.screenshot({path:'/tmp/playground-share-mobile.png'})
  await a.locator('.pg-share-person').filter({hasText:'Bob'}).getByRole('button',{name:'Remove',exact:true}).click()
  await a.getByRole('alertdialog').getByRole('button',{name:'Remove',exact:true}).click()
  await b.getByText(/Access was removed or expired/).waitFor()
  await b.getByRole('button', {name:'Leave session',exact:true}).click()
  await a.getByRole('button', {name:'Leave session',exact:true}).click()
  await a.route('**/api/session/config',route=>route.fulfill({contentType:'application/json',body:'{"enabled":false}'}))
  await a.reload()
  await a.getByRole('button',{name:'Share files',exact:true}).click()
  await a.getByText('1 file',{exact:false}).waitFor()
  await a.getByRole('button',{name:'Open',exact:true}).click()
  assert.equal(await a.getByRole('button',{name:'Download',exact:true}).isEnabled(),true)
  await a.screenshot({path:'/tmp/playground-share-desktop.png'})
  await a.context().close(); await b.context().close()
})

test('Outlook is excluded and merely visiting an app never joins a room', async () => {
  const page = await appPage('/mailcraft/')
  assert.equal(await page.locator('.pg-share').count(), 0)
  await page.context().close()
  const idle = await appPage()
  await idle.getByRole('button', {name:'Share files',exact:true}).waitFor({timeout:3000})
  assert.equal(await idle.locator('.pg-share-count').textContent(), 'Share')
  await idle.context().close()
})

test('an unavailable service reports an error without losing the selected files', async () => {
  const page = await appPage()
  await page.getByRole('button', {name:'Share files',exact:true}).click({timeout:3000})
  await page.locator('input[type=file]').setInputFiles({name:'safe.txt',mimeType:'text/plain',buffer:Buffer.from('safe')})
  await page.route('**/api/session/*/create', route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Session service unavailable'})}))
  await page.getByRole('button', {name:'Create session',exact:true}).click()
  await page.getByRole('alert').filter({hasText:'Session service unavailable'}).waitFor()
  assert.equal(await page.locator('input[type=file]').evaluate(el=>el.files[0].name), 'safe.txt')
  await page.context().close()
})

